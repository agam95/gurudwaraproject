let hukamnamaRefreshTimeoutId;

const getSelectedLanguage = (lang) => (lang === "sv" ? "sv" : (translations[lang] ? lang : "sv"));

const getPageKey = () => {
  const path = window.location.pathname.toLowerCase();
  return path.endsWith("protokoll.html") ? "page_title_protocols" : "page_title_home";
};

const getLocalizedField = (value, lang, fallback = "sv") => {
  if (typeof value === "string" || typeof value === "number") {
    return String(value);
  }

  if (value && typeof value === "object") {
    return value[lang] || value[fallback] || Object.values(value).find((item) => typeof item === "string") || "";
  }

  return "";
};

const updateDocumentTitle = (lang) => {
  const selectedLanguage = getSelectedLanguage(lang);
  const pageKey = getPageKey();
  document.title = selectedLanguage === "sv" ? defaultTexts[pageKey] : translations[selectedLanguage][pageKey];
};

const getDayOfYear = (date) => {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const millisecondsPerDay = 24 * 60 * 60 * 1000;
  return Math.floor((date - startOfYear) / millisecondsPerDay);
};

const getHukamnamaRotationDate = () => {
  const rotationDate = new Date();
  rotationDate.setMinutes(rotationDate.getMinutes() - 1);
  return rotationDate;
};

const applyDailyHukamnama = (lang) => {
  const selectedLanguage = getSelectedLanguage(lang);
  const entries = fallbackContent[selectedLanguage].hukamnama || fallbackContent.sv.hukamnama;
  const rotationDate = getHukamnamaRotationDate();
  const entryIndex = getDayOfYear(rotationDate) % entries.length;
  const currentEntry = entries[entryIndex];

  if (hukamnamaQuoteNode && currentEntry?.quote) {
    hukamnamaQuoteNode.textContent = currentEntry.quote;
  }

  if (hukamnamaTextNode && currentEntry?.text) {
    hukamnamaTextNode.textContent = currentEntry.text;
  }

  if (hukamnamaLinkNode) {
    hukamnamaLinkNode.href = externalHukamnamaUrl;
    hukamnamaLinkNode.target = "_blank";
    hukamnamaLinkNode.rel = "noreferrer";
  }
};

const scheduleDailyHukamnamaRefresh = () => {
  if (hukamnamaRefreshTimeoutId) {
    window.clearTimeout(hukamnamaRefreshTimeoutId);
  }

  const now = new Date();
  const nextRefresh = new Date(now);
  nextRefresh.setHours(0, 1, 0, 0);

  if (now >= nextRefresh) {
    nextRefresh.setDate(nextRefresh.getDate() + 1);
  }

  hukamnamaRefreshTimeoutId = window.setTimeout(() => {
    applyDailyHukamnama(document.documentElement.lang || localStorage.getItem("preferredLanguage") || "sv");
    scheduleDailyHukamnamaRefresh();
  }, (nextRefresh.getTime() - now.getTime()) + 100);
};

const normalizeItem = (item, fields) => {
  const normalized = {};
  fields.forEach((field) => {
    normalized[field] = item?.[field] ?? "";
  });
  return normalized;
};

const normalizeCollection = (rawItems, fields, fallbackItems) => {
  if (!Array.isArray(rawItems) || !rawItems.length) {
    return fallbackItems.slice();
  }

  return rawItems.map((item, index) => {
    const fallbackItem = fallbackItems[index] || {};
    const normalized = normalizeItem(item, fields);
    fields.forEach((field) => {
      if (normalized[field] === "" || normalized[field] === null) {
        normalized[field] = fallbackItem[field] ?? "";
      }
    });
    return normalized;
  });
};

const renderPrograms = (lang) => {
  if (!programListNode) {
    return;
  }

  const selectedLanguage = getSelectedLanguage(lang);
  const items = editableContent.programs.length ? editableContent.programs : fallbackContent[selectedLanguage].programs || fallbackContent.sv.programs;

  programListNode.innerHTML = "";

  items.forEach((item) => {
    const article = document.createElement("article");
    article.className = "program-card";

    const day = document.createElement("span");
    day.textContent = getLocalizedField(item.day, selectedLanguage);

    const title = document.createElement("h3");
    title.textContent = getLocalizedField(item.title, selectedLanguage);

    const description = document.createElement("p");
    description.textContent = getLocalizedField(item.description, selectedLanguage);

    article.append(day, title, description);

    const linkUrl = item.link_url || "";
    const linkLabel = getLocalizedField(item.link_label, selectedLanguage);
    const time = getLocalizedField(item.time, selectedLanguage);

    if (linkUrl && linkLabel) {
      const link = document.createElement("a");
      link.className = "program-link";
      link.href = linkUrl;

      const strong = document.createElement("strong");
      strong.textContent = linkLabel;
      link.appendChild(strong);
      article.appendChild(link);
    } else if (time) {
      const strong = document.createElement("strong");
      strong.textContent = time;
      article.appendChild(strong);
    }

    programListNode.appendChild(article);
  });
};

const renderDocuments = (lang) => {
  if (!documentListNode) {
    return;
  }

  const selectedLanguage = getSelectedLanguage(lang);
  const items = editableContent.documents.length ? editableContent.documents : fallbackContent[selectedLanguage].documents || fallbackContent.sv.documents;

  documentListNode.innerHTML = "";

  items.forEach((item) => {
    const article = document.createElement("article");
    article.className = "protocol-card";

    const meta = document.createElement("span");
    meta.className = "protocol-meta";
    meta.textContent = getLocalizedField(item.meta, selectedLanguage);

    const title = document.createElement("h3");
    title.textContent = getLocalizedField(item.title, selectedLanguage);

    const summary = document.createElement("p");
    summary.textContent = getLocalizedField(item.summary, selectedLanguage);

    article.append(meta, title, summary);

    const label = getLocalizedField(item.link_label, selectedLanguage);
    const file = item.file || "";

    if (file) {
      const link = document.createElement("a");
      link.className = "protocol-link";
      link.href = file;
      link.textContent = label;
      link.target = "_blank";
      link.rel = "noreferrer";
      article.appendChild(link);
    } else if (label) {
      const placeholder = document.createElement("span");
      placeholder.className = "protocol-link";
      placeholder.textContent = label;
      article.appendChild(placeholder);
    }

    documentListNode.appendChild(article);
  });
};

