const fetchContentFile = async (path) => {
  const response = await fetch(path, { cache: "no-store" });
  if (!response.ok) {
    throw new Error(`Could not load ${path}`);
  }
  return response.json();
};

const loadEditableContent = async () => {
  try {
    const [programData, documentData] = await Promise.all([
      fetchContentFile("data/programs.json"),
      fetchContentFile("data/documents.json")
    ]);

    editableContent.programs = normalizeCollection(
      programData.items,
      ["day", "title", "description", "time", "link_url", "link_label"],
      fallbackContent.sv.programs
    );

    editableContent.documents = normalizeCollection(
      documentData.items,
      ["meta", "title", "summary", "link_label", "file"],
      fallbackContent.sv.documents
    );
  } catch (error) {
    console.error("Failed to load editable content.", error);
    editableContent.programs = fallbackContent.sv.programs.slice();
    editableContent.documents = fallbackContent.sv.documents.slice();
  }

  refreshLocalizedContent(document.documentElement.lang || localStorage.getItem("preferredLanguage") || "sv");
};

