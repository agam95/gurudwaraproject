const setLanguage = (lang) => {
  const selectedLanguage = lang === "sv" ? "sv" : (translations[lang] ? lang : "sv");
  const locale = selectedLanguage === "sv" ? defaultTexts : translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  localStorage.setItem("preferredLanguage", selectedLanguage);

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (locale[key]) {
      node.textContent = decodeText(locale[key]);
    }
  });

  attributeNodes.forEach((node) => {
    const mappings = node.dataset.i18nAttr.split(",");
    mappings.forEach((mapping) => {
      const [attribute, key] = mapping.split(":").map((part) => part.trim());
      const value = selectedLanguage === "sv" ? defaultAttributes[key] : locale[key];
      if (attribute && key && value) {
        node.setAttribute(attribute, decodeText(value));
      }
    });
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", isActive ? "true" : "false");
  });

  applyDailyHukamnama(selectedLanguage);
};

