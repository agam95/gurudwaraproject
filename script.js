const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector(".nav-links");
const backToTop = document.querySelector(".back-to-top");
const revealElements = document.querySelectorAll(".reveal");
const languageButtons = document.querySelectorAll(".lang-btn");
const textNodes = document.querySelectorAll("[data-i18n]");
const attributeNodes = document.querySelectorAll("[data-i18n-attr]");
const defaultTexts = {};
const defaultAttributes = {};

const decodeText = (text) => {
  const textarea = document.createElement("textarea");
  textarea.innerHTML = text;
  return textarea.value;
};

textNodes.forEach((node) => {
  defaultTexts[node.dataset.i18n] = node.textContent;
});

attributeNodes.forEach((node) => {
  node.dataset.i18nAttr.split(",").forEach((mapping) => {
    const [attribute, key] = mapping.split(":").map((part) => part.trim());
    if (attribute && key) {
      defaultAttributes[key] = node.getAttribute(attribute);
    }
  });
});

const setLanguage = (lang) => {
  const selectedLanguage = lang === "sv" ? "sv" : (translations[lang] ? lang : "sv");
  const locale = selectedLanguage === "sv" ? defaultTexts : translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  localStorage.setItem("preferredLanguage", selectedLanguage);

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (locale[key]) {
      node.textContent = decodeText(locale[key]);
    }
  });

  attributeNodes.forEach((node) => {
    const mappings = node.dataset.i18nAttr.split(",");
    mappings.forEach((mapping) => {
      const [attribute, key] = mapping.split(":").map((part) => part.trim());
      const value = selectedLanguage === "sv" ? defaultAttributes[key] : locale[key];
      if (attribute && key && value) {
        node.setAttribute(attribute, decodeText(value));
      }
    });
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", isActive ? "true" : "false");
  });
};

menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", isOpen);
});

navLinks.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

const revealOnScroll = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      revealOnScroll.unobserve(entry.target);
    }
  });
}, { threshold: 0.14 });

revealElements.forEach((element) => revealOnScroll.observe(element));

